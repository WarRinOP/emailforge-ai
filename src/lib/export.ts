// Types
export interface EmailObject {
  position: number;
  send_timing: string;
  subject_lines: [string, string];
  body: string;
  purpose: string;
}

export interface SequenceRecord {
  id: string;
  offer: string;
  target_audience: string;
  sequence_type: string;
  tone: string;
  email_count: number;
  sender_name?: string | null;
  company_name?: string | null;
  emails: EmailObject[];
  created_at: string;
  updated_at: string;
}

// Sequence type display labels
export const SEQUENCE_LABELS: Record<string, string> = {
  cold_outreach: "Cold Outreach",
  follow_up: "Follow-Up",
  welcome_drip: "Welcome Drip",
  re_engagement: "Re-engagement",
  sales_nurture: "Sales Nurture",
};

export const TONE_LABELS: Record<string, string> = {
  professional: "Professional",
  conversational: "Conversational",
  direct: "Direct",
  friendly: "Friendly",
};

/**
 * Format a full sequence as a downloadable .txt string.
 */
export function formatSequenceExport(sequence: SequenceRecord): string {
  const typeLabel = SEQUENCE_LABELS[sequence.sequence_type] ?? sequence.sequence_type;
  const toneLabel = TONE_LABELS[sequence.tone] ?? sequence.tone;
  const date = new Date(sequence.created_at).toLocaleDateString("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });
  const total = sequence.emails.length;

  const divider = "──────────────────────────────────────────";
  const header = "══════════════════════════════════════════";

  const lines: string[] = [
    "",
    "  EmailForge Sequence Export",
    header,
    "",
    `  Offer:    ${sequence.offer}`,
    `  Audience: ${sequence.target_audience}`,
    `  Type:     ${typeLabel}`,
    `  Tone:     ${toneLabel}`,
    sequence.sender_name ? `  Sender:   ${sequence.sender_name}` : "",
    sequence.company_name ? `  Company:  ${sequence.company_name}` : "",
    `  Generated: ${date}`,
    "",
    header,
    "",
  ].filter((l) => l !== null);

  for (const email of sequence.emails) {
    lines.push(divider);
    lines.push(
      `  EMAIL ${email.position} OF ${total}  —  ${email.send_timing}`
    );
    lines.push(divider);
    lines.push("");
    lines.push(`  Subject A: ${email.subject_lines[0]}`);
    lines.push(`  Subject B: ${email.subject_lines[1]}`);
    lines.push("");
    lines.push(`  Goal: ${email.purpose}`);
    lines.push("");
    // Indent each line of the body
    const bodyLines = email.body.split("\n").map((l) => `  ${l}`);
    lines.push(...bodyLines);
    lines.push("");
  }

  lines.push(header);
  lines.push("  Generated by EmailForge");
  lines.push(header);
  lines.push("");

  return lines.join("\n");
}

/**
 * Generate a filename slug for the export.
 */
export function generateExportFilename(sequence: SequenceRecord): string {
  const typeSlug = sequence.sequence_type.replace(/_/g, "-");
  const dateStr = new Date(sequence.created_at)
    .toISOString()
    .slice(0, 10)
    .replace(/-/g, "");
  return `emailforge-${typeSlug}-${dateStr}.txt`;
}
